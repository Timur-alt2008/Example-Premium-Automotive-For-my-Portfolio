export const brands = Array.from(new Set(cars.map((c) => c.brand))).sort();

export function carBySlug(slug: string): Car | undefined {
  return cars.find((c) => c.slug === slug);
}

export function carName(car: Car): string {
  return `${car.brand} ${car.model}`;
}

/** Cars that share a category with the given car, closest price first. */
export function similarCars(car: Car, limit = 3): Car[] {
  return cars
    .filter((c) => c.slug !== car.slug && c.categories.some((cat) => car.categories.includes(cat)))
    .sort((a, b) => Math.abs(a.pricePerDay - car.pricePerDay) - Math.abs(b.pricePerDay - car.pricePerDay))
    .slice(0, limit);
}

